function normalizeTitle(title: string) {
  return title.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-zA-Z0-9]+/g, " ").trim().toLowerCase();
}

export function getEditionMedia(title: string): EditionMedia | null {
  const slug = titleToSlug[normalizeTitle(title)];
  return slug ? editionMediaBySlug[slug] ?? null : null;
}
